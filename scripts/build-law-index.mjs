// Regenerates src/lawindex.ts from gesetze-im-internet.de.
//
// Why this exists: the app turns a model-written citation ("§ 551 BGB") into a link
// to the official text. Nothing stopped it linking a section that does not exist —
// a 404 presented to the reader as an official source. This fetches the real table
// of contents of every law we map and records which section numbers are real, so an
// invented citation degrades to plain text instead of a broken official link.
//
// Run: node scripts/build-law-index.mjs   (only when the law list changes)

import fs from "node:fs";

const SLUGS = JSON.parse(fs.readFileSync("scripts/law-slugs.json", "utf8"));

const out = {};
for (const [abbr, slug] of Object.entries(SLUGS)) {
  const url = `https://www.gesetze-im-internet.de/${slug}/index.html`;
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`FAIL ${abbr} (${slug}): HTTP ${res.status}`);
    continue;
  }
  // The site is still served as ISO-8859-1.
  const html = new TextDecoder("iso-8859-1").decode(await res.arrayBuffer());
  const nums = [...new Set([...html.matchAll(/__(\d+[a-z]*)\.html/g)].map((m) => m[1]))];
  nums.sort((a, b) => (parseInt(a) - parseInt(b)) || a.localeCompare(b));
  if (nums.length === 0) {
    console.error(`FAIL ${abbr} (${slug}): no section links found`);
    continue;
  }
  out[abbr] = nums.join(",");
  console.error(`ok ${abbr.padEnd(10)} ${String(nums.length).padStart(5)} sections`);
}

const body = `// GENERATED by scripts/build-law-index.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand. Source: https://www.gesetze-im-internet.de (amtliche Fassung).
//
// One entry per law we can link: every section number that actually exists in it.
// Used to refuse a link for a citation no such section supports — see contract.ts.

const RAW: Record<string, string> = ${JSON.stringify(out, null, 2)};

const INDEX = new Map<string, Set<string>>(
  Object.entries(RAW).map(([law, list]) => [law, new Set(list.split(","))]),
);

/** True when \`section\` ("551", "312g") is a real section of \`law\` ("bgb"). */
export function sectionExists(law: string, section: string): boolean {
  return INDEX.get(law)?.has(section) ?? false;
}

/** True when we hold an index for this law at all. */
export function lawIndexed(law: string): boolean {
  return INDEX.has(law);
}
`;
fs.writeFileSync("src/lawindex.ts", body);
console.error(`\nwrote src/lawindex.ts — ${Object.keys(out).length} laws, ${(body.length / 1024).toFixed(0)} KB`);
